#!/usr/bin/env python3
"""Generate ruse's Vim character-class table from the pinned Neovim (#745).

Vim's `\\<` / `\\>` (`nfa_regmatch` NFA_BOW / NFA_EOW) and the keyword `*` / `#` pick up (nvim's
`find_ident_at_pos`) do not use Unicode word boundaries. They compare `mb_get_class` of two adjacent
characters, which is:

  * below U+0100: 0 for NUL, space, tab and U+00A0; 2 for an 'iskeyword' character; 1 otherwise;
  * from U+0100: `utf_class`, i.e. 3 for an emoji, the entry of nvim's `classes[]` table when the
    character is in it (0 blank, 1 punctuation, or a per-script value such as 0x3040 Hiragana,
    0x30A0 Katakana, 0x4E00 CJK, 0xAC00 Hangul, 0x2070 superscripts), else 2 (a word character).

So `\\<한` matches in "abc한글" (Latin class 2 next to Hangul class 0xAC00) and `\\<API\\>` matches
"API" in "API를". The table is CAPTURED, never hand-written: nvim's `charclass()` returns
`mb_get_class` of its argument, so it is asked for every code point, in a `-u NONE` session whose
'iskeyword' is the default "@,48-57,_,192-255" (which makes Latin-1 `×` and `÷` word characters).

The generated Rust file holds the runs of code points whose class is not 2, with their class.

Usage:
    python3 tools/parity/char_classes.py            # regenerate crates/core/src/char_class_table.rs
    python3 tools/parity/char_classes.py --check    # fail if the committed file is stale
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT = REPO_ROOT / "crates" / "core" / "src" / "char_class_table.rs"
sys.path.insert(0, str(Path(__file__).resolve().parent))

import oracle  # noqa: E402

# Lua: `charclass()` of every scalar value from U+0001 (NUL cannot be passed in a string; it is
# class 0, `mb_get_class`'s first test). Emits [first, last, class] runs of the classes that are not 2.
_NVIM_LUA = r"""
local function enc(c)
  if c < 0x80 then return string.char(c)
  elseif c < 0x800 then return string.char(0xC0 + bit.rshift(c, 6), 0x80 + bit.band(c, 0x3F))
  elseif c < 0x10000 then
    return string.char(0xE0 + bit.rshift(c, 12), 0x80 + bit.band(bit.rshift(c, 6), 0x3F), 0x80 + bit.band(c, 0x3F))
  end
  return string.char(0xF0 + bit.rshift(c, 18), 0x80 + bit.band(bit.rshift(c, 12), 0x3F),
    0x80 + bit.band(bit.rshift(c, 6), 0x3F), 0x80 + bit.band(c, 0x3F))
end
local charclass = vim.fn.charclass
local runs = { { 0, 0, 0 } }
for c = 1, 0x10FFFF do
  if c < 0xD800 or c > 0xDFFF then
    local k = charclass(enc(c))
    if k ~= 2 then
      local last = runs[#runs]
      if last[3] == k and last[2] == c - 1 then
        last[2] = c
      else
        runs[#runs + 1] = { c, c, k }
      end
    end
  end
end
io.write(vim.json.encode({ runs = runs, iskeyword = vim.o.iskeyword }))
"""

DEFAULT_ISKEYWORD = "@,48-57,_,192-255"


def run_nvim() -> dict:
    oracle.assert_pin(oracle.nvim_version(), oracle.read_pin())
    with tempfile.TemporaryDirectory() as tmp:
        script = Path(tmp) / "probe.lua"
        script.write_text(_NVIM_LUA, encoding="utf-8")
        proc = subprocess.run(
            ["nvim", "--headless", "-u", "NONE", "-i", "NONE", "-l", str(script)],
            capture_output=True,
            text=True,
            timeout=600,
        )
    if proc.returncode != 0 or not proc.stdout:
        raise SystemExit(f"nvim probe failed (rc={proc.returncode}): {proc.stderr.strip()}")
    return json.loads(proc.stdout)


def render(probe: dict, nvim_ver: str) -> str:
    if probe["iskeyword"] != DEFAULT_ISKEYWORD:
        raise SystemExit(f"unexpected 'iskeyword' {probe['iskeyword']!r}; want {DEFAULT_ISKEYWORD!r}")
    out: list[str] = []
    w = out.append
    w("// @generated by tools/parity/char_classes.py. Do not edit; rerun the script instead.")
    w(f"// Neovim: {nvim_ver}, `charclass()` of every code point, 'iskeyword' {DEFAULT_ISKEYWORD}.")
    w("")
    w(f'pub(crate) const NVIM_VERSION: &str = "{nvim_ver}";')
    w("")
    w("/// Runs `(first, last, class)` of the code points whose Vim class (`mb_get_class`) is not 2, the")
    w("/// word class; sorted, disjoint. Surrogates are not scalar values and do not appear.")
    w("pub(crate) const NVIM_CLASS_RUNS: &[(u32, u32, u32)] = &[")
    for a, b, k in probe["runs"]:
        w(f"    (0x{a:X}, 0x{b:X}, 0x{k:X}),")
    w("];")
    return "\n".join(out) + "\n"


def generate() -> str:
    return render(run_nvim(), oracle.nvim_version())


def main(argv: list[str]) -> int:
    text = generate()
    if "--check" in argv:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO_ROOT)} is stale: rerun tools/parity/char_classes.py", file=sys.stderr)
            return 1
        print("character-class table is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
